# Lists
numbers = [10, 20, 30, 40]
print(numbers[0])
print(numbers[-1])
numbers.append(50)
print(numbers)

# 2D list
matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]
print(matrix[1][2])

# Tuples
point = (5, 10)
print(point[0])

# Sets
items = {"apple", "banana", "apple"}
print(items)

# Dictionaries
student = {
    "name": "Zameer",
    "age": 21,
    "branch": "CSE"
}
print(student["name"])
print(student.get("age"))
